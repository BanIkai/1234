#pragma once
#include <Arduino.h>

// =============================================================================
//  Motors.h — ควบคุมมอเตอร์ซ้าย-ขวา ผ่านไดรเวอร์ A4950
// =============================================================================

namespace Motors {

  // เรียกครั้งเดียวใน setup() เพื่อตั้งค่าขา OUTPUT
  void begin();

  // สั่งความเร็วมอเตอร์แบบ sign-magnitude
  //   left, right : -255 (ถอยเต็มที่) ถึง +255 (หน้าเต็มที่)
  //   0           : เบรก (หยุดทันที)
  void drive(int left, int right);

  // เบรกแข็ง — ใส่ HIGH ทั้งสองขาของแต่ละช่อง (A4950 brake mode)
  void brake();

  // ปล่อยล้อ (coast) — ใส่ LOW ทุกขา ใช้เมื่อถูก Kill
  void coast();

}
