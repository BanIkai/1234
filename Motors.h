#pragma once

// ============================================================
//  Motors.h — ประกาศ API ของมอเตอร์
//
//  ไฟล์นี้คือ "สารบัญ" บอกว่ามีฟังก์ชันอะไรใช้ได้บ้าง
//  โค้ดจริงอยู่ใน Motors.cpp
//
//  วิธีเรียกใช้จากไฟล์อื่น:
//    Motors::begin();          ← เรียกครั้งเดียวใน setup()
//    Motors::move(200, 200);   ← เดินหน้าเต็มสปีด
//    Motors::move(-200, 200);  ← หมุนซ้าย
//    Motors::stop();           ← หยุดทั้งคู่
//
//  ค่าความเร็ว:
//    +255 = เดินหน้าเต็มสปีด
//    -255 = ถอยหลังเต็มสปีด
//       0 = หยุด
// ============================================================

namespace Motors {

  // เตรียมขามอเตอร์ — เรียกใน setup() ครั้งเดียว
  void begin();

  // สั่งความเร็วมอเตอร์ซ้าย/ขวา (ค่า -255 ถึง +255)
  void move(int leftSpeed, int rightSpeed);

  // หยุดทั้งสองมอเตอร์ (เหมือนเรียก move(0, 0))
  void stop();

}
