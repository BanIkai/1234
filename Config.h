// ── ขา (PIN) ของมอเตอร์ ──────────────────────────────────────
//
//  มอเตอร์แต่ละตัวต้องการ 2 ขา คือ ขา "เดินหน้า" และ ขา "ถอยหลัง"
//  ถ้าต่อสายมอเตอร์ผิดขา แก้ตัวเลขที่นี่ได้เลย

#define PIN_L1  11   // มอเตอร์ซ้าย — ขา "เดินหน้า"
#define PIN_L2  10   // มอเตอร์ซ้าย — ขา "ถอยหลัง"
#define PIN_R1   5   // มอเตอร์ขวา  — ขา "เดินหน้า"
#define PIN_R2   6   // มอเตอร์ขวา  — ขา "ถอยหลัง"


// ── ขา (PIN) ของ Sensor ตรวจเส้น ────────────────────────────
//
//  Sensor เส้นจะอ่านค่า 0–1023 ผ่าน analogRead()
//  ถ้าค่าที่อ่านได้ "มากกว่า Threshold" → แปลว่าเจอเส้นขาว (ออกนอกสนาม)
//
//  วิธีหา Threshold ที่เหมาะสม:
//    1. เปิด Serial Monitor
//    2. วาง sensor บนพื้นดำ → จด leftRaw, rightRaw
//    3. วาง sensor บนเส้นขาว → จด leftRaw, rightRaw
//    4. ตั้ง Threshold ให้อยู่กึ่งกลางระหว่าง 2 ค่านั้น

#define PIN_LINE_L   A2    // ขา sensor เส้นซ้าย
#define PIN_LINE_R   A7    // ขา sensor เส้นขวา

#define LINE_L_TH   920   // Threshold เส้นซ้าย  (analogRead > ค่านี้ = เจอเส้น)
#define LINE_R_TH   500   // Threshold เส้นขวา  (ขวาต่ำกว่าซ้ายเพราะ sensor คนละรุ่น)


// ── ขา (PIN) ของ Sensor ระยะ Sharp GP2Y0A41SK0F ─────────────
//
//  ติดตั้งทั้งหมด 5 ตัว รอบหัวหุ่น:
//
//       [SL]  [FL] [FC] [FR]  [SR]
//        ซ้าย  หน้า หน้า หน้า  ขวา
//              ซ้าย กลาง ขวา
//
//  ข้อควรระวัง: อย่าใช้ขา A2 และ A7 เพราะใช้ sensor เส้นไปแล้ว

#define PIN_SHARP_SL  A0   // sensor ด้านข้างซ้าย
#define PIN_SHARP_FL  A1   // sensor หน้าซ้าย
#define PIN_SHARP_FC  A3   // sensor หน้ากลาง
#define PIN_SHARP_FR  A4   // sensor หน้าขวา
#define PIN_SHARP_SR  A5   // sensor ด้านข้างขวา


// ── ค่าขีดจำกัดของ Sensor ระยะ ──────────────────────────────
//
//  Sensor ตัวนี้วัดได้แม่นยำในช่วง 40–300 mm เท่านั้น
//  ถ้าวัดได้นอกช่วงนี้ โค้ดจะถือว่า "ไม่มีวัตถุ"

#define SHARP_MAX_MM   300   // ระยะไกลสุดที่เชื่อถือได้ (mm)
#define SHARP_MIN_MM    40   // ระยะใกล้สุดที่เชื่อถือได้ (mm)
#define SHARP_SAMPLES    3   // อ่านค่ากี่ครั้งแล้วเฉลี่ย (เพิ่มเพื่อลด noise)


// ── ระยะที่ใช้ตัดสินใจ (หน่วย mm) ──────────────────────────
//
//  RAM_DIST   — ถ้าศัตรูใกล้กว่านี้ → "พุ่งชนเลย!" (เต็มสปีด)
//  TRACK_DIST — ถ้าศัตรูอยู่ในช่วงนี้ → "เลี้ยวตาม" (ยังไม่พุ่ง)
//  SIDE_DIST  — ระยะที่ sensor ข้างถือว่า "เห็นศัตรู"
//
//  ตัวอย่าง: ถ้าอยาก aggressive ขึ้น → เพิ่ม RAM_DIST

#define RAM_DIST    180   // ระยะพุ่งชน (mm)
#define TRACK_DIST  280   // ระยะที่ "เห็น" ศัตรู (mm)
#define SIDE_DIST   200   // ระยะ sensor ข้างที่นับว่าเจอ (mm)


// ── ความเร็วมอเตอร์ (0 = หยุด, 255 = เร็วสุด) ───────────────
//
//  ถ้าหุ่นไม่หมุนตามศัตรูดีพอ → ลด TRACK_SLOW ลง (เพิ่มความต่าง)
//  ถ้าหุ่นหมุนค้นหาเร็วเกินไป → ลด SEARCH_SPEED ลง

#define ATTACK_SPEED  255   // พุ่งชน — เต็มสปีด

#define TRACK_FAST    220   // ติดตาม — ล้อด้านที่หันหาศัตรู
#define TRACK_SLOW    130   // ติดตาม — ล้อด้านตรงข้าม (ยิ่งต่างกันมาก ยิ่งหักเลี้ยวแรง)

#define SEARCH_SPEED  100   // ความเร็วตอนค้นหาศัตรู
#define ESCAPE_BACK   200   // ถอยหนีเส้น
#define ESCAPE_TURN   200   // หมุนกลับเข้าสนาม


// ── เวลา (หน่วย ms = มิลลิวินาที) ──────────────────────────
//
//  1000 ms = 1 วินาที
//
//  ถ้าหุ่นถอยหนีเส้นน้อยเกินไปแล้วตก → เพิ่ม ESCAPE_BACK_MS
//  ถ้าหมุนกลับแล้วหันหน้าออกนอกสนาม  → ปรับ ESCAPE_TURN_MS

#define ESCAPE_BACK_MS   180   // ถอยหลังนานแค่ไหน
#define ESCAPE_TURN_MS   220   // หมุนกลับนานแค่ไหน

#define LOCK_TIME        500   // จำตำแหน่งศัตรูไว้นานแค่ไหน หลังมองไม่เห็น
#define SEARCH_SWAP_MS   600   // หมุนค้นหาทิศละกี่ ms ก่อนสลับ
#define SEARCH_FWD_MS    200   // เดินหน้าก่อนหมุนค้นหา (ทำให้ครอบคลุมพื้นที่มากขึ้น)


// ── ค่าพิเศษ ─────────────────────────────────────────────────

// ถ้า sensor หน้าซ้าย (fl) และหน้าขวา (fr) ต่างกันน้อยกว่านี้
// ถือว่าศัตรูอยู่ตรงหน้าพอดี → วิ่งตรงไปเลย ไม่ต้องเลี้ยว
#define TRACK_CENTER_ZONE  40

// ค่าที่แทนความหมาย "ไม่เจอวัตถุ" หรือ "sensor อ่านค่าไม่ได้"
// ใช้ 999 เพราะเกินระยะสูงสุดของ sensor (300 mm) มาก
#define NO_TARGET  999
